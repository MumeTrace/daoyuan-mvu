import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { mkdtemp, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
const origin = process.env.MAP_TEST_URL || 'http://127.0.0.1:5182/';
const builtMode = process.env.EMBEDDED_BUILD === '1';
const builtHtml = builtMode ? JSON.parse(await readFile(new URL('../dist/regex-mvu.json', import.meta.url), 'utf8')).replaceString.replace(/^`{3,}html\r?\n/, '').replace(/\r?\n`{3,}$/, '') : '';
const output = await mkdtemp(path.join(tmpdir(), 'daoyuan-host-overlay-'));
const fixture = '<svg xmlns="http://www.w3.org/2000/svg" width="720" height="1080"><rect width="720" height="1080" fill="#416080"/><rect y="0" width="720" height="80" fill="#bc8ecb"/><rect y="1000" width="720" height="80" fill="#77bb99"/><text x="80" y="520" font-size="60" fill="white">FULL PORTRAIT</text></svg>';
try {
  for (const width of [1280, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, isMobile: width < 600, hasTouch: width < 600, deviceScaleFactor: width < 600 ? 3 : 1 });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', route => {
      const url = route.request().url();
      if (url === `${origin}__host`) return route.fulfill({ contentType: 'text/html', body: `<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><style>body{margin:0;background:#312435}h2{color:red!important}section{max-width:100px}#shell{width:340px;height:430px;overflow:hidden;transform:translate(12px,20px);border:3px solid red}iframe{width:100%;height:100%;border:0}</style><div id="shell"><iframe src="${origin}"></iframe></div>` });
      if (url === origin && builtMode) return route.fulfill({ contentType: 'text/html', body: builtHtml });
      if (url.startsWith(origin)) return route.continue();
      if (route.request().resourceType() === 'image') return route.fulfill({ contentType: 'image/svg+xml', body: fixture });
      return route.abort();
    });
    await page.goto(`${origin}__host`);
    const child = page.frames().find(frame => frame !== page.mainFrame());
    await child.getByRole('button', { name: '舆图', exact: true }).click();
    const frameBox = await page.locator('iframe').boundingBox();
    if (builtMode) {
      // Tavern renderers may move the inlined stylesheet to body.
      await child.evaluate(() => { const css = document.head.querySelector('style'); if (css) document.body.append(css); });
      await child.getByRole('button', { name: '展开地图', exact: true }).click();
      const expanded = page.locator('[data-daoyuan-overlay-host] .dy-atlas-expanded');
      const map = await expanded.evaluate(element => ({ box: element.getBoundingClientRect().toJSON(), frame: element.querySelector('.dy-atlas-frame').getBoundingClientRect().toJSON(), display: getComputedStyle(element).display, background: getComputedStyle(element).backgroundColor, markerFill: getComputedStyle(element.querySelector('.dy-atlas-marker-hit')).fill, headingSize: getComputedStyle(element.querySelector('h2')).fontSize }));
      assert.equal(Math.round(map.box.width), width);
      assert.equal(Math.round(map.box.height), 900);
      assert.ok(map.frame.height >= 900 * .6, JSON.stringify(map));
      assert.equal(map.display, 'flex');
      assert.equal(map.background, 'rgb(16, 21, 33)');
      assert.notEqual(map.markerFill, 'rgb(0, 0, 0)');
      assert.ok(parseFloat(map.headingSize) >= 26, JSON.stringify(map));
      await page.screenshot({ path: path.join(output, `${width}-built-map.png`), animations: 'disabled' });
      await page.getByRole('button', { name: '收起地图', exact: true }).click();
      assert.equal(await page.locator('[data-daoyuan-overlay-host]').count(), 0);
      assert.deepEqual(await page.locator('iframe').boundingBox(), frameBox);
      // A map entry opened from the small, non-expanded iframe must still use the host viewport.
      await child.locator('[data-region="center"]').focus();
      await page.keyboard.press('Enter');
      const regionOverlay = page.locator('[data-daoyuan-overlay-host] .dy-map-location-overlay');
      await regionOverlay.waitFor();
      const regionBox = await regionOverlay.boundingBox();
      assert.equal(Math.round(regionBox.width), width);
      assert.equal(Math.round(regionBox.height), 900);
      const regionDialog = page.getByRole('dialog', { name: '中央神州', exact: true });
      const dialogBox = await regionDialog.boundingBox();
      assert.ok(dialogBox.x >= 0 && dialogBox.y >= 0 && dialogBox.x + dialogBox.width <= width + 1 && dialogBox.y + dialogBox.height <= 901);
      await page.screenshot({ path: path.join(output, `${width}-built-region.png`), animations: 'disabled' });
      await regionDialog.locator('.map-loc-img-wrapper img').click();
      assert.equal(Math.round((await page.locator('#image-modal-overlay').boundingBox()).height), 900);
      await page.keyboard.press('Escape');
      await regionDialog.waitFor();
      await regionDialog.locator('.faction-tag').first().click();
      const factionOverlay = page.locator('[data-daoyuan-overlay-host] .dy-map-faction-overlay');
      await factionOverlay.waitFor();
      const factionBox = await factionOverlay.boundingBox();
      assert.equal(Math.round(factionBox.height), 900);
      const factionDialog = factionOverlay.locator('.faction-modal-content');
      const factionDialogBox = await factionDialog.boundingBox();
      assert.ok(factionDialogBox.y >= 0 && factionDialogBox.y + factionDialogBox.height <= 901);
      await page.screenshot({ path: path.join(output, `${width}-built-faction.png`), animations: 'disabled' });
      await factionOverlay.locator('.faction-modal-close').click();
      await regionDialog.waitFor();
      await regionDialog.getByRole('button', { name: '关闭地域详情' }).click();
      assert.equal(await page.locator('[data-daoyuan-overlay-host]').count(), 0);
      await child.locator('[data-marker="center:大周仙朝"]').focus();
      await page.keyboard.press('Enter');
      await factionOverlay.waitFor();
      assert.equal(Math.round((await factionOverlay.boundingBox()).height), 900);
      await factionOverlay.locator('.faction-modal-close').click();
      assert.equal(await page.locator('[data-daoyuan-overlay-host]').count(), 0);
      assert.deepEqual(errors, []);
      await page.close();
      continue;
    }
    await child.evaluate(async () => {
      window.__overlayTestIdentity = 'same-frame-instance';
      window.getCharWorldbookNames = () => ({ primary: '守护者资料', additional: [] });
      window.getWorldbook = async () => [{ uid: 1, name: '紫澪', enabled: true, strategy: { keys: ['紫澪'] }, content: '姓名：紫澪\n身份：蓬莱仙岛守护者\n种族：冥煞玄蛇\n性格：冷静' }];
      const { pinia } = await import('/stores/pinia.ts');
      const { useImageLibraryStore } = await import('/stores/image-library.ts');
      const { usePortraitStore } = await import('/stores/portraits.ts');
      await usePortraitStore(pinia).initialize();
      useImageLibraryStore(pinia).setLibrary({ data: { entities: { 紫澪: { type: 'character', images: [{ theme: 'default', url: 'https://example.org/full-portrait.svg' }] } } } }, 'host-test');
    });
    await child.getByRole('button', { name: '展开地图', exact: true }).click();
    const expanded = page.locator('[data-daoyuan-overlay-host] .dy-atlas-expanded');
    await expanded.waitFor();
    const box = await expanded.boundingBox();
    assert.equal(Math.round(box.width), width);
    assert.equal(Math.round(box.height), 900);
    assert.ok((await expanded.locator('.dy-atlas-frame').boundingBox()).height >= 900 * .6);
    assert.deepEqual(await page.locator('iframe').boundingBox(), frameBox, 'Do not resize or reparent the source iframe');
    await page.locator('[data-marker="special_east"]').focus();
    await page.keyboard.press('Enter');
    await page.getByRole('dialog', { name: '蓬莱仙岛', exact: true }).waitFor();
    assert.equal(Math.round((await page.locator('.dy-map-location-overlay').boundingBox()).height), 900);
    await page.locator('.dy-map-location-dialog .faction-tag').click();
    await page.locator('.dy-guardian-image img').waitFor();
    assert.equal(Math.round((await page.locator('.dy-map-faction-overlay').boundingBox()).height), 900);
    const fit = await page.locator('.dy-guardian-image img').evaluate(img => ({ fit: getComputedStyle(img).objectFit, width: img.clientWidth, height: img.clientHeight, parentHeight: img.closest('.dy-guardian-image').clientHeight }));
    assert.equal(fit.fit, 'contain');
    assert.ok(fit.height <= fit.parentHeight + 1, JSON.stringify(fit));
    await page.screenshot({ path: path.join(output, `${width}-guardian.png`), animations: 'disabled' });
    await page.getByRole('button', { name: '全屏查看紫澪立绘', exact: true }).click();
    const imageBox = await page.locator('#image-modal-overlay').boundingBox();
    assert.equal(Math.round(imageBox.width), width);
    assert.equal(Math.round(imageBox.height), 900);
    const img = page.locator('#modal-image');
    await img.hover(); await page.mouse.wheel(0, -100);
    const previous = await img.getAttribute('style');
    await page.mouse.down(); await page.mouse.move(width / 2 + 35, 485); await page.mouse.up();
    assert.notEqual(await img.getAttribute('style'), previous, 'Dragging is listened to on the host window');
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: '查看紫澪人物详情', exact: true }).click();
    await page.getByRole('dialog', { name: '查看角色设定', exact: true }).waitFor();
    await page.getByRole('button', { name: '确定查看', exact: true }).click();
    await page.getByText('✨【紫澪】· 天机命理', { exact: true }).waitFor();
    assert.match(await page.locator('.faction-modal-body').textContent(), /冥煞玄蛇/);
    await page.locator('#faction-modal-overlay .faction-modal-close').click();
    await page.getByRole('button', { name: '全屏查看紫澪立绘', exact: true }).waitFor();
    await page.locator('#faction-modal-overlay .faction-modal-close').click();
    await page.getByRole('button', { name: '关闭地域详情', exact: true }).click();
    await page.getByRole('button', { name: '收起地图', exact: true }).click();
    assert.equal(await page.locator('[data-daoyuan-overlay-host]').count(), 0);
    assert.equal(await child.evaluate(() => window.__overlayTestIdentity), 'same-frame-instance');
    assert.equal(await page.evaluate(() => document.body.style.overflow), '');
    assert.deepEqual(await page.locator('iframe').boundingBox(), frameBox);
    // Images opened without a fullscreen map acquire and release the same host.
    await child.evaluate(async () => {
      const { pinia } = await import('/stores/pinia.ts'); const { useUiStore } = await import('/stores/ui.ts');
      useUiStore(pinia).openImageModal('https://example.org/full-portrait.svg');
    });
    await page.getByRole('dialog', { name: '全屏图片查看器', exact: true }).waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('[data-daoyuan-overlay-host]').count(), 0);
    assert.deepEqual(errors, []);
    await page.close();
  }
  console.log(`${builtMode ? 'BUILT_HOST_STYLE_OK' : 'HOST_OVERLAY_OK'} desktop/mobile. Screenshots: ${output}`);
} finally { await browser.close(); }
